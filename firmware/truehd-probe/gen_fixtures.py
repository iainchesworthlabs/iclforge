#!/usr/bin/env python3
"""Writes main/fixtures.inc: the TrueHD fixtures the probe decodes and the PCM hash each must give.

    python gen_fixtures.py

The streams are embedded from testdata/truehd by main/CMakeLists.txt (EMBED_FILES); the hashes
are testdata/truehd/manifest.json's pcm_sha256, the SHA-256 of FFmpeg's strict decode as 32-bit
little-endian samples (the 24-bit value shifted left by 8), channels interleaved.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CHOSEN = [
    "truehd_mono48_s24",
    "truehd_st48_s16",
    "truehd_st48_s24",
    "truehd_st44_s24",
    "truehd_st96_s24",
    "truehd_st192_s24",
    "truehd_m51_s16",
    "truehd_m51_s24",
]


def main() -> None:
    manifest = json.loads((ROOT / "testdata" / "truehd" / "manifest.json").read_text())
    by_name = {f["name"]: f for f in manifest["fixtures"]}
    lines = ["// Generated by gen_fixtures.py from testdata/truehd/manifest.json. Do not edit.", ""]
    for name in CHOSEN:
        symbol = by_name[name]["file"].replace(".", "_").replace("-", "_")
        for edge in ("start", "end"):
            label = f"_binary_{symbol}_{edge}"
            lines.append(f'extern const unsigned char {label}[] asm("{label}");')
    lines.append("")
    lines.append("constexpr Fixture kFixtures[] = {")
    for name in CHOSEN:
        f = by_name[name]
        symbol = f["file"].replace(".", "_").replace("-", "_")
        lines.append(
            f'    {{"{name}", _binary_{symbol}_start, _binary_{symbol}_end, '
            f'{f["sample_rate"]}, {f["channels"]}, {f["bits"]}, {f["access_units"]}, '
            f'{f["pcm_samples"]}, "{f["pcm_sha256"]}"}},'
        )
    lines.append("};")
    (HERE / "main" / "fixtures.inc").write_text("\n".join(lines) + "\n")
    print("wrote main/fixtures.inc,", len(CHOSEN), "fixtures")


if __name__ == "__main__":
    main()
