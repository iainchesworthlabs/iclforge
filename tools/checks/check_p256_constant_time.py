#!/usr/bin/env python3
"""Run ECDSA signing under valgrind with the private scalar marked secret (ctgrind).

libs/base/src/crypto/p256_math.hpp is written to take the same time and touch the same memory
whatever the key and digest are. That is a property of machine code, and a compiler may undo it, so
this check builds the signing code the way the library is built (optimised, from the same sources)
and has memcheck report every conditional jump or address that depends on the secret scalar.

A few reports are expected and are the only ones allowed. They are branches on an event whose
probability is 2^-32 or smaller by construction, or on a fact about the output that is public:

  rfc6979_nonce      RFC 6979 section 3.2 step h.3: a candidate nonce that is not below the group
                     order is discarded and another drawn. Probability about 2^-32 for P-256.
  to_affine          the result is the point at infinity or not. For a key in 1..n-1 it never is,
                     so the branch is always the same way and says nothing.
  ecdsa_sign         r = 0 or s = 0 restarts the signature (FIPS 186-4 section 6.3). Probability
                     about 2^-256.
  from_uncompressed  the validity checks on the public key the secret produced, which is a public
                     output.

Any other report, in particular one inside mont_mul, mont_inverse, scalar_multiply, point_add or
point_double, fails the check. The script exits 0 when only the allowed reports occur, 1 when
another occurs or the run does not complete, and 77 when valgrind or a C++ compiler is missing.

    tools/checks/check_p256_constant_time.py [--cxx g++] [--flags "-O3 -DNDEBUG"]
"""

import argparse
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

REPO = pathlib.Path(__file__).resolve().parents[2]
BASE = REPO / "libs" / "base"

# (function the report is in, at the top of its stack) that are allowed, with the file it must be
# in. A report is matched on its innermost frame, which valgrind names after inlining.
ALLOWED = {
    ("rfc6979_nonce", "p256.cpp"),
    ("to_affine", "p256_math.hpp"),
    ("ecdsa_sign", "p256.cpp"),
    ("from_uncompressed", "p256.cpp"),
}

SOURCES = [
    "libs/base/src/crypto/p256.cpp",
    "libs/base/src/crypto/sha256.cpp",
    "libs/base/src/crypto/hmac_sha256.cpp",
]


def short_function(name: str) -> str:
    """'iclforge::base::crypto::detail::to_affine(...)' -> 'to_affine'."""
    name = name.split("(")[0]
    return name.split("::")[-1].strip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--cxx", default=os.environ.get("CXX", "g++"))
    parser.add_argument("--flags", default="-O3 -DNDEBUG",
                        help="optimisation flags; use the ones the library is released with")
    args = parser.parse_args()

    if shutil.which("valgrind") is None or shutil.which(args.cxx) is None:
        print("skip: valgrind or the C++ compiler is not installed")
        return 77

    with tempfile.TemporaryDirectory() as work:
        work_dir = pathlib.Path(work)
        binary = work_dir / "p256_constant_time"
        # iclforge/base/export.hpp is generated by the build (GenerateExportHeader). The sources
        # are compiled straight into the check program here, so the export macro is empty, and a
        # stand-in header says so; the check then needs no build tree.
        stand_in = work_dir / "include" / "iclforge" / "base"
        stand_in.mkdir(parents=True)
        (stand_in / "export.hpp").write_text("#pragma once\n#define ICLFORGE_BASE_EXPORT\n")
        command = [args.cxx, "-std=c++23", "-g", *args.flags.split(),
                   f"-I{BASE / 'include'}", f"-I{BASE / 'src' / 'crypto'}",
                   f"-I{work_dir / 'include'}"]
        command += [str(REPO / "tools" / "checks" / "p256_constant_time.cpp"),
                    *[str(REPO / s) for s in SOURCES], "-o", str(binary)]
        build = subprocess.run(command, capture_output=True, text=True)
        if build.returncode != 0:
            print("error: the check program did not build:")
            print(build.stderr)
            return 1

        xml_path = work_dir / "memcheck.xml"
        run = subprocess.run(["valgrind", "--tool=memcheck", "--error-limit=no", "--xml=yes",
                              f"--xml-file={xml_path}", "--num-callers=12", str(binary)],
                             capture_output=True, text=True)
        print(run.stdout.strip())
        if run.returncode != 0:
            print(f"error: the program exited with {run.returncode}")
            print(run.stderr)
            return 1

        tree = ET.parse(xml_path)
        unexpected = []
        seen = set()
        for error in tree.getroot().iter("error"):
            kind = error.findtext("kind")
            frames = error.find("stack").findall("frame")
            top = frames[0]
            function = short_function(top.findtext("fn") or "?")
            file = top.findtext("file") or "?"
            line = top.findtext("line") or "?"
            key = (function, file)
            seen.add(key)
            if key not in ALLOWED:
                unexpected.append((kind, function, file, line))

        if unexpected:
            print("error: memcheck reports a use of the secret in a place that is not allowed:")
            for kind, function, file, line in unexpected:
                print(f"  {kind} in {function} ({file}:{line})")
            return 1
        missing = ALLOWED - seen
        # An allowed site that no longer reports is fine (the code got better) but worth saying,
        # because the allowance can then be dropped.
        for function, file in sorted(missing):
            print(f"note: no report from {function} ({file}); the allowance can be removed")
        print("ok: the only uses of the secret in a branch or an address are the allowed ones "
              f"({len(seen)} site(s) reported)")
        return 0


if __name__ == "__main__":
    sys.exit(main())
