#!/usr/bin/env python3
"""Make the files to hand to Dolby's web-based StreamValidator by hand.

The Online Delivery Kit's StreamValidator is a web page that runs in the browser and takes .mpd,
.m3u8, .mp4, .m4a, .ts or a .zip of manifests and media, with a Decryption box for key id:key
pairs. It is hosted on ott.dolby.com, and from the sandbox this project's automated work runs in it
answered HTTP 403 AccessDenied to a default headless Chromium on both addresses the kit names, so
no script here drives it. This script writes what a person puts into it from their own browser:

    python3 tools/checks/dolby_validator_bundle.py --cli build/bin/forge --out /path/to/dir

It writes, under --out, a folder `validator-bundle/` and `validator-bundle.zip`:

    clear/<codec>.{ac3,ec3,ac4}      elementary streams: AC-3, E-AC-3, E-AC-3 JOC, AC-4
    mp4/<codec>.mp4                  progressive MP4
    dash/<codec>.zip, hls/<codec>.zip   the fragmented-MP4 set with its manifest or playlists
    ts/<codec>_<profile>.ts          MPEG-2 transport streams
    protected/<codec>_<scheme>.mp4   test-key protected MP4s (needs python's `cryptography`)
    keys.txt                         the key id:key pair for the protected files, test values only
    README.txt                       the checklist, with a table to write each verdict into

Everything is generated by forge from signals it synthesises or from the committed object fixture.
Nothing in it comes from Dolby's kit. Exit status: 0 on success, 1 on an error.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

import dolby_odk_corpus as corpus

KID = "a1b2c3d4e5f60718293a4b5c6d7e8f90"
KEY = "00112233445566778899aabbccddeeff"
SCHEMES = ("cenc", "cbc1", "cens", "cbcs")
GENERATOR = corpus.REPO / "tools" / "generators" / "cenc_make_protected.py"

CHECKLIST = """\
Dolby StreamValidator: manual run of the files in this bundle
==============================================================

The validator runs entirely in the browser; local files are not uploaded. Use a fresh private
window, and clear the browser cache first, as the kit says. Open the validator from the Online
Delivery Kit's own help page. Each file or .zip below goes in as one run.

 1. clear/*.ac3, *.ec3, *.ac4   (elementary streams; the validator takes the ones it supports)
 2. mp4/*.mp4                   (progressive MP4)
 3. dash/*.zip                  (manifest.mpd + init + segments)
 4. hls/*.zip                   (master.m3u8, audio.m3u8 + init + segments)
 5. ts/*.ts
 6. protected/*.mp4             tick Decryption, enter the pair in keys.txt, run. Also run each
                                once with no key, and once with a wrong key, and note the answer.

Write one line per run in this table and paste it into docs/verification.md, section
"Findings from Dolby's tools". Say whether the validator printed PASSED or FAILED and copy the
error class and message (usage, compliance, invalid attribute).

| file | validator version / date | result | error class and message |
|---|---|---|---|

The keys in keys.txt are test values made up for this bundle. The files are made by forge and
contain no Dolby material.
"""


def build(cli: str, out: Path) -> list[str]:
    notes: list[str] = []
    root = out / "validator-bundle"
    if root.exists():
        shutil.rmtree(root)
    (root / "clear").mkdir(parents=True)
    streams, problems = corpus.make_streams(cli, root / "_work" / "streams")
    notes += problems
    for stream in streams:
        shutil.copy(stream.path, root / "clear" / f"{stream.name}{stream.path.suffix}")
        files = corpus.make_containers(cli, stream, root / "_work" / stream.name)
        for key, folder, target in (("mp4", "mp4", f"{stream.name}.mp4"),):
            if key in files:
                (root / folder).mkdir(exist_ok=True)
                shutil.copy(files[key], root / folder / target)
        for leg in ("ts_dvb", "ts_atsc"):
            if leg in files:
                (root / "ts").mkdir(exist_ok=True)
                shutil.copy(files[leg], root / "ts" / f"{stream.name}_{leg[3:]}.ts")
        if "dash" in files:
            for kind, names in (
                ("dash", ("manifest.mpd", "init.mp4", "segment*.m4s")),
                ("hls", ("master.m3u8", "audio.m3u8", "init.mp4", "segment*.m4s")),
            ):
                (root / kind).mkdir(exist_ok=True)
                folder = files["dash"].parent
                with zipfile.ZipFile(root / kind / f"{stream.name}.zip", "w") as zf:
                    for pattern in names:
                        for member in sorted(folder.glob(pattern)):
                            zf.write(member, member.name)
        if "mp4" in files:
            for scheme in SCHEMES:
                target = root / "protected" / f"{stream.name}_{scheme}.mp4"
                target.parent.mkdir(exist_ok=True)
                made = subprocess.run(
                    [sys.executable, str(GENERATOR), str(files["mp4"]), str(target), scheme],
                    capture_output=True,
                    text=True,
                    check=False,
                )
                if made.returncode != 0:
                    notes.append(f"{stream.name} {scheme}: {made.stderr.strip()[-100:]}")
    shutil.rmtree(root / "_work")
    (root / "keys.txt").write_text(f"{KID}:{KEY}\n")
    (root / "README.txt").write_text(CHECKLIST)
    archive = out / "validator-bundle.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for member in sorted(root.rglob("*")):
            if member.is_file():
                zf.write(member, member.relative_to(out))
    return notes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--cli", default=corpus.default_cli(), help="forge binary (default $ICLFORGE_CLI)"
    )
    parser.add_argument(
        "--out", required=True, help="directory to write validator-bundle/ and the zip into"
    )
    args = parser.parse_args(argv)
    if not args.cli:
        parser.error("--cli or ICLFORGE_CLI is required")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    notes = build(args.cli, out)
    for note in notes:
        print(f"note: {note}", file=sys.stderr)
    print(out / "validator-bundle.zip")
    return 1 if notes else 0


if __name__ == "__main__":
    sys.exit(main())
