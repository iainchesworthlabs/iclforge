#!/usr/bin/env python3
"""The Hearth sink screen's tokens: one file, one generated output, two checked sources.

planning/hearth-sink-screen.md fixes the family's tokens once and planning/hearth-android.md (D13)
says where: docs/hearth/design/sink-screen-tokens.json. This script

  * writes the Android app's Tokens.kt from it (--write) and holds the committed copy to it
    (--check);
  * holds the desktop's Signal dark palette (apps/shared/theme/assets/qml/Theme.qml) and the P4X
    panel's screen (firmware/hearth-sink/main/panel/lvgl/lyric_screen.cpp) to the same values,
    without writing to either: they are other programs' files, and a drift is reported with the
    value each holds.

Exit status 0 when everything agrees, 1 with a line per disagreement otherwise.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "docs/hearth/design/sink-screen-tokens.json"
KOTLIN = ROOT / "apps/hearth/android/app/src/main/java/com/iclforge/hearth/Tokens.kt"
QML = ROOT / "apps/shared/theme/assets/qml/Theme.qml"
PANEL = ROOT / "firmware/hearth-sink/main/panel/lvgl/lyric_screen.cpp"
# The panel's sizes are the display's (iclforge::screen::metrics_for): the kit's 1024 by 600 is
# its first block.
METRICS = ROOT / "libs/device/include/iclforge/screen_metrics.hpp"

# Theme.qml's names for the rungs of Signal dark that the sink screen uses.
QML_RUNGS = {
    "bg": "bg",
    "surface": "surface",
    "text": "text",
    "accent": "accent",
    "surface_up": "n200",
    "rule": "n300",
    "faint": "n400",
    "muted": "n600",
}
# lyric_screen.cpp's constants for the colours.
PANEL_COLOURS = {
    "bg": "kBg",
    "surface": "kSurface",
    "surface_up": "kSurfaceUp",
    "text": "kText",
    "accent": "kAccent",
    "muted": "kMuted",
    "faint": "kFaint",
}


def load(path: Path = TOKENS) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def argb(hex_rgb: str) -> str:
    return "0xFF" + hex_rgb.upper()


def kotlin(tokens: dict) -> str:
    """Tokens.kt as text: what the generator writes and the check compares the file with."""
    c = tokens["colours"]
    lay = tokens["layout"]
    cur = tokens["current_line"]
    delay = tokens["delay"]
    tim = tokens["timing"]
    fps = tokens["frames_per_second"]
    height = tokens["canvas"]["height"]
    width = tokens["canvas"]["width"]
    sung = tokens["sung_opacity_percent"]
    sung_alpha = round(sung * 255 / 100)
    sizes = cur["sizes"]
    limits = cur["max_characters"]
    max_delay = f"{delay['max_ms']:,}"
    out = f"""\
// GENERATED by tools/checks/sink_screen_tokens.py from docs/hearth/design/sink-screen-tokens.json.
// Do not edit: change the file and run `python3 tools/checks/sink_screen_tokens.py --write`.
package com.iclforge.hearth

/**
 * The family's tokens as planning/hearth-sink-screen.md (Tokens, Layout) states them: the Signal
 * palette in its dark mode, which a sink always draws, whatever the OS theme is, and the sizes in
 * `u`, a 600th of the view's height. The desktop's palette and the P4X panel's screen are held to
 * the same file by the same script.
 */
object Tokens {{
    val BG: Int = {argb(c["bg"])}.toInt()
    val SURFACE: Int = {argb(c["surface"])}.toInt()
    val SURFACE_UP: Int = {argb(c["surface_up"])}.toInt()
    val TEXT: Int = {argb(c["text"])}.toInt()
    val ACCENT: Int = {argb(c["accent"])}.toInt()
    val MUTED: Int = {argb(c["muted"])}.toInt()
    val FAINT: Int = {argb(c["faint"])}.toInt()
    val RULE: Int = {argb(c["rule"])}.toInt()

    /** A line already sung: the accent at {sung}% (3.5:1 on `BG`; 55% was 2.6:1), D13. */
    val SUNG: Int = (0x{sung_alpha:02X} shl 24) or (ACCENT and 0x00FFFFFF)

    // The reference canvas is {width} by {height} u and a surface sets u = height / {height}.
    const val CANVAS_HEIGHT_U = {height}f
    const val MARGIN_U = {lay["margin"]}f
    const val HEADER_U = {lay["header"]}f
    const val FOOTER_U = {lay["footer"]}f
    const val PAST_U = {lay["past"]}f
    const val NEXT_U = {lay["next"]}f
    const val SMALL_U = {lay["small"]}f
    const val TRACKING_U = {lay["tracking_tenths"] / 10}f
    const val ROW_GAP_U = {lay["row_gap"]}f
    const val HAIRLINE_U = {lay["hairline"]}f

    /** The smallest touch or focus target, in u. */
    const val MIN_TARGET_U = {lay["min_target"]}f

    /** A duet's second vocal is indented this fraction of the width (the desktop's rule). */
    const val DUET_INDENT = {lay["duet_indent_percent"] / 100}f

    /** Android TV's overscan margin on each side, on top of the margin (the spec's table). */
    const val OVERSCAN = {lay["overscan_percent"] / 100}f

    /** The count-in: four dots that go out one a second. */
    const val DOT_U = {lay["dot"]}f
    const val DOT_GAP_U = {lay["dot_gap"]}f

    /** The lyric delay: -{max_delay} to +{max_delay} ms in {delay["step_ms"]} ms steps (SS6). */
    const val DELAY_STEP_MS = {delay["step_ms"]}
    const val DELAY_MAX_MS = {delay["max_ms"]}

    /** The grace a document that is a moment behind the stream gets before "no lyrics" (S7). */
    const val NO_LYRICS_GRACE_MS = {tim["no_lyrics_grace_ms"]}L

    /** The controls sheet hides itself after this long without a key (S9). */
    const val SHEET_HIDE_MS = {tim["sheet_hide_ms"]}L

    /** The idle screen's rule: after this long unchanged it dims and starts to move (Motion). */
    const val IDLE_QUIET_MS = {tim["idle_quiet_ms"]}L
    const val IDLE_STEP_MS = {tim["idle_step_ms"]}L
    const val IDLE_DIMMED = {tim["idle_dimmed_percent"] / 100}f
    const val IDLE_STEP_U = {tim["idle_step_u"]}f

    private val SIZES = intArrayOf({", ".join(str(s) for s in sizes)})
    private val MAX_CHARACTERS = intArrayOf({", ".join(str(n) for n in limits)})

    /** The most rows the line being sung wraps to (SS1). */
    const val CURRENT_MAX_ROWS = {cur["max_rows"]}

    /**
     * The size the current line is drawn at, in u: the panel's rule by the line's length in
     * characters, not a measurement (up to {limits[0]} characters {sizes[0]} u, up to {limits[1]} \
{sizes[1]} u, up to {limits[2]} {sizes[2]} u, up to
     * {limits[3]} {sizes[3]} u, longer {sizes[4]} u), then the singer's text size step (0 small, \
1 medium, 2 large)
     * one step down or up.
     */
    fun currentSizeU(characters: Int, step: Int = 1): Float {{
        var index = MAX_CHARACTERS.indexOfFirst {{ characters <= it }}
        if (index < 0) {{
            index = MAX_CHARACTERS.size
        }}
        if (step == 0) {{
            index = minOf(index + 1, SIZES.size - 1)
        }} else if (step == 2 && index > 0) {{
            index -= 1
        }}
        return SIZES[index].toFloat()
    }}

    /** Frames a second for a frame: {fps["singing"]} while a word is sung, {fps["line"]} while a \
line is shown, {fps["idle"]} when idle. */
    fun framesPerSecond(frame: LyricFrame): Int = when {{
        frame.singing -> {fps["singing"]}
        frame.mode == LyricFrame.Mode.LINE || frame.mode == LyricFrame.Mode.GAP ||
            frame.mode == LyricFrame.Mode.WAITING -> {fps["line"]}
        else -> {fps["idle"]}
    }}
}}
"""
    return out


def check_qml(tokens: dict, text: str) -> list[str]:
    """Signal dark's rungs in Theme.qml against the colours."""
    where = QML.relative_to(ROOT)
    found = re.search(r"signal:\s*\{.*?dark:\s*\{(.*?)\}", text, re.S)
    if not found:
        return [f"{where}: no signal.dark palette found"]
    palette = dict(re.findall(r'\b([a-z]+\d*)\s*:\s*"#([0-9a-fA-F]{6})"', found.group(1)))
    problems = []
    for name, rung in QML_RUNGS.items():
        want = tokens["colours"][name].lower()
        have = palette.get(rung, "").lower()
        if have != want:
            problems.append(
                f"{where}: signal dark {rung} is #{have or '(missing)'}, "
                f"the tokens' {name} is #{want}"
            )
    return problems


def _number(text: str, name: str) -> int | None:
    pattern = rf"constexpr\s+[\w:]+\s+{name}\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;"
    found = re.search(pattern, text)
    return int(found.group(1), 0) if found else None


def check_panel(tokens: dict, text: str) -> list[str]:
    """The panel's constants against the colours, the layout and the delay."""
    where = PANEL.relative_to(ROOT)
    problems = []

    for name, constant in PANEL_COLOURS.items():
        have = _number(text, constant)
        want = int(tokens["colours"][name], 16)
        if have != want:
            shown = "missing" if have is None else f"0x{have:06X}"
            problems.append(
                f"{where}: {constant} is {shown}, the tokens' {name} is 0x{want:06X}"
            )
    lay = tokens["layout"]
    canvas_width = tokens["canvas"]["width"]
    expected = {
        "kDuetIndent": round(canvas_width * lay["duet_indent_percent"] / 100),
        "kDelayStepMs": tokens["delay"]["step_ms"],
        "kDelayMaxMs": tokens["delay"]["max_ms"],
        "kSheetIdleMs": tokens["timing"]["sheet_hide_ms"],
    }
    for constant, want in expected.items():
        have = _number(text, constant)
        if have != want:
            problems.append(f"{where}: {constant} is {have}, the tokens say {want}")
    opacity = _number(text, "kSungOpacity")
    percent = tokens["sung_opacity_percent"]
    want_opacity = round(percent * 255 / 100)
    if opacity is None or abs(opacity - want_opacity) > 2:
        problems.append(
            f"{where}: kSungOpacity is {opacity}, {percent}% is {want_opacity} of 255"
        )
    sizes = re.search(r"kSizes\s*\{([^}]*)\}", text)
    have_sizes = [int(n) for n in re.findall(r"\d+", sizes.group(1))] if sizes else None
    want_sizes = tokens["current_line"]["sizes"]
    if have_sizes != want_sizes:
        problems.append(f"{where}: the line sizes are {have_sizes}, the tokens say {want_sizes}")
    return problems


def check_metrics(tokens: dict, text: str) -> list[str]:
    """The sizes the panel is drawn at on the kit's canvas, against the layout tokens."""
    where = METRICS.relative_to(ROOT)
    canvas = tokens["canvas"]
    # The first block of metrics_for(): the one for a display whose shorter side is the canvas's.
    block = re.search(r"shorter\s*>=\s*(\d+)\s*\)\s*\{(.*?)\}", text, re.S)
    if block is None or int(block.group(1)) > min(canvas["width"], canvas["height"]):
        size = f"{canvas['width']} by {canvas['height']}"
        return [f"{where}: metrics_for() has no block for the canvas, {size}"]
    lay = tokens["layout"]
    expected = {
        "margin": lay["margin"],
        "header": lay["header"],
        "footer": lay["footer"],
        "text": lay["small"],
        "target": lay["min_target"],
    }
    problems = []
    for name, want in expected.items():
        found = re.search(rf"\.{name}\s*=\s*(\d+)", block.group(2))
        have = int(found.group(1)) if found else None
        if have != want:
            problems.append(f"{where}: the canvas's {name} is {have}, the tokens say {want}")
    return problems


def _shown(path: Path) -> str:
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def check(
    tokens_path: Path = TOKENS,
    kotlin_path: Path = KOTLIN,
    qml_path: Path = QML,
    panel_path: Path = PANEL,
    metrics_path: Path = METRICS,
) -> list[str]:
    tokens = load(tokens_path)
    problems = []
    want = kotlin(tokens)
    have = None
    if kotlin_path.exists():
        have = kotlin_path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if have != want:
        problems.append(
            f"{_shown(kotlin_path)} is not current: "
            "run python3 tools/checks/sink_screen_tokens.py --write"
        )
    sources = ((qml_path, check_qml), (panel_path, check_panel), (metrics_path, check_metrics))
    for path, check_one in sources:
        if not path.exists():
            problems.append(f"{path}: not found")
            continue
        problems.extend(check_one(tokens, path.read_text(encoding="utf-8").replace("\r\n", "\n")))
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true", help="write the generated Tokens.kt")
    parser.add_argument("--check", action="store_true", help="the default: hold all to the tokens")
    args = parser.parse_args(argv)
    if args.write:
        KOTLIN.write_text(kotlin(load()), encoding="utf-8", newline="\n")
        print(f"sink_screen_tokens: wrote {KOTLIN.relative_to(ROOT)}")
    problems = check()
    for problem in problems:
        print(f"::error::sink_screen_tokens: {problem}")
    print(f"sink_screen_tokens: {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
