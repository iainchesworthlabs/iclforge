#!/usr/bin/env python3
"""Generate libs/base/tests/p256_vectors.inc, the known-answer vectors for the in-tree P-256 code.

The C++ under test (libs/base/src/crypto/p256_math.hpp and p256.cpp) is written from the standards,
so its answers need an independent oracle. This script supplies two:

  * Python's arbitrary-precision integers, for field and scalar arithmetic: a product mod p, a sum,
    a difference and an inverse are one line each and are not worth getting wrong in two languages.
  * OpenSSL, through the `cryptography` package, for everything that involves a curve point: it
    derives k*G, and it is asked to verify every signature this script writes, so a vector in the
    file is a signature OpenSSL accepts (or, in the invalid group, one it rejects).

The ECDSA signatures are made here with fixed nonces from an RFC 6979 implementation written in
Python (section 3.2, HMAC-SHA-256). It is deliberately not shared with the C++ one: the C++ test
checks that both derive the same k, r and s, which is what shows the C++ follows the RFC. RFC 6979's
own Appendix A.2.5 values are checked in C++ as well, from the RFC text, apart from this file.

The output is deterministic (a fixed seed, no random nonce), so the committed file changes only when
this script does. Run it from anywhere:

    python3 tools/generators/gen_p256_vectors.py

It needs `cryptography` (any release with ec.derive_private_key). Nothing here is a secret: the
private scalars are derived from fixed strings and exist to be public test data.
"""

import hashlib
import hmac
import pathlib
import random
import sys

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import Prehashed, encode_dss_signature

# FIPS 186-4 D.1.2.3 / the specification's section 2.2.
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551

OUT = pathlib.Path(__file__).resolve().parents[2] / "libs" / "base" / "tests" / "p256_vectors.inc"


def hex32(value: int) -> str:
    return f"{value:064X}"


def public_point(scalar: int):
    """k*G as (x, y), by OpenSSL."""
    key = ec.derive_private_key(scalar, ec.SECP256R1())
    numbers = key.public_key().public_numbers()
    return numbers.x, numbers.y


def rfc6979_k(d: int, digest: bytes) -> int:
    """RFC 6979 section 3.2 for P-256 and SHA-256: qlen = hlen = 256, so bits2octets is `h1 mod q`."""
    h1 = int.from_bytes(digest, "big") % N
    x = d.to_bytes(32, "big")
    h = h1.to_bytes(32, "big")
    v = b"\x01" * 32
    k = b"\x00" * 32
    k = hmac.new(k, v + b"\x00" + x + h, hashlib.sha256).digest()
    v = hmac.new(k, v, hashlib.sha256).digest()
    k = hmac.new(k, v + b"\x01" + x + h, hashlib.sha256).digest()
    v = hmac.new(k, v, hashlib.sha256).digest()
    while True:
        v = hmac.new(k, v, hashlib.sha256).digest()
        candidate = int.from_bytes(v, "big")
        if 1 <= candidate < N:
            return candidate
        k = hmac.new(k, v + b"\x00", hashlib.sha256).digest()
        v = hmac.new(k, v, hashlib.sha256).digest()


def sign_with_nonce(d: int, digest: bytes, k: int):
    e = int.from_bytes(digest, "big")
    rx, _ = public_point(k)
    r = rx % N
    s = pow(k, -1, N) * (e + r * d) % N
    return r, s


def openssl_accepts(qx: int, qy: int, digest: bytes, r: int, s: int) -> bool:
    """Whether OpenSSL verifies (r, s) over the 32-byte digest. r and s outside 1..n-1 cannot be
    DER-encoded by a library that checks, so they are reported as rejected without asking."""
    if not (1 <= r < N and 1 <= s < N):
        return False
    public = ec.EllipticCurvePublicNumbers(qx, qy, ec.SECP256R1()).public_key()
    try:
        public.verify(encode_dss_signature(r, s), digest, ec.ECDSA(Prehashed(hashes.SHA256())))
        return True
    except InvalidSignature:
        return False


def main() -> int:
    rng = random.Random("ac4-content-signing p256 vectors")
    lines = []
    emit = lines.append
    emit("// Generated by tools/generators/gen_p256_vectors.py. Do not edit; rerun the script.")
    emit("// clang-format off")
    emit("// Field and scalar arithmetic by Python integers, curve points and signature acceptance by")
    emit("// OpenSSL (see the script). Every value is 32 bytes as 64 uppercase hexadecimal digits.")
    emit("")

    # --- Modular arithmetic: {modulus, a, b, a*b, a+b, a-b, a^-1} --------------------------------
    emit("// {modulus (0 = p, 1 = n), a, b, a*b mod m, a+b mod m, a-b mod m, a^-1 mod m (0 for 0)}")
    emit("inline constexpr FieldVector kFieldVectors[] = {")
    for which, m in ((0, P), (1, N)):
        edge = [0, 1, 2, 3, m - 1, m - 2, m - 3, 2**255, 2**255 - 1, 2**256 - m, (m - 1) // 2,
                (m + 1) // 2, 2**128, 2**128 - 1, 0xFFFFFFFF, 2**224]
        values = list(edge)
        while len(values) < 56:
            values.append(rng.randrange(0, m))
        pairs = [(a, b) for a in edge for b in (0, 1, m - 1, 2**255)]
        pairs += [(rng.choice(values), rng.choice(values)) for _ in range(120)]
        pairs += [(a, a) for a in values[:20]]
        for a, b in pairs:
            inverse = pow(a, -1, m) if a else 0
            emit(f'    {{{which}, "{hex32(a)}", "{hex32(b)}", "{hex32(a * b % m)}", '
                 f'"{hex32((a + b) % m)}", "{hex32((a - b) % m)}", "{hex32(inverse)}"}},')
    emit("};")
    emit("")

    # --- Scalar multiplication: {k, x, y} -----------------------------------------------------
    edge_scalars = [1, 2, 3, 4, 5, 7, 8, 15, 16, 17, 255, 256, 65535, 65536, 2**32, 2**64 - 1,
                    2**64, 2**128, 2**224, 2**255 - 1, 2**255, 2**255 + 1, (N - 1) // 2,
                    (N + 1) // 2, N - 3, N - 2, N - 1, P % N, 2**256 - 2**224, 2**256 - N]
    scalars = [k for k in edge_scalars if 1 <= k < N]
    scalars += [rng.randrange(1, N) for _ in range(64)]
    # Scalars with long runs of ones and zeros exercise the carries and the window scan.
    scalars += [int("1" * 128 + "0" * 128, 2) % N, int("0" * 128 + "1" * 128, 2) % N,
                int("10" * 128, 2) % N, int("01" * 128, 2) % N]
    emit("// {k, x(kG), y(kG)}")
    emit("inline constexpr PointVector kPointVectors[] = {")
    for k in scalars:
        x, y = public_point(k)
        emit(f'    {{"{hex32(k)}", "{hex32(x)}", "{hex32(y)}"}},')
    emit("};")
    emit("")

    # --- ECDSA with RFC 6979 nonces: {d, qx, qy, digest, k, r, s} -------------------------------
    emit("// {d, Qx, Qy, digest, k (RFC 6979), r, s}; OpenSSL verifies (r, s) under Q")
    emit("inline constexpr SignVector kSignVectors[] = {")
    keys = [1, 2, N - 1, 0xC9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721]
    keys += [rng.randrange(1, N) for _ in range(28)]
    for i, d in enumerate(keys):
        digest = hashlib.sha256(f"message {i}".encode()).digest()
        if i < 3:
            digest = [b"\x00" * 32, b"\xff" * 32, (N - 1).to_bytes(32, "big")][i]
        qx, qy = public_point(d)
        k = rfc6979_k(d, digest)
        r, s = sign_with_nonce(d, digest, k)
        if not openssl_accepts(qx, qy, digest, r, s):
            print(f"error: OpenSSL rejects the signature of vector {i}", file=sys.stderr)
            return 1
        emit(f'    {{"{hex32(d)}", "{hex32(qx)}", "{hex32(qy)}", "{digest.hex().upper()}", '
             f'"{hex32(k)}", "{hex32(r)}", "{hex32(s)}"}},')
    emit("};")
    emit("")

    # --- Verification, valid and invalid: {Qx, Qy, digest, r, s, valid} -------------------------
    emit("// {Qx, Qy, digest, r, s, valid}; `valid` is OpenSSL's verdict, and is false for any r or s")
    emit("// outside 1..n-1. Each group holds the cases of one way a verifier goes wrong.")
    emit("inline constexpr VerifyVector kVerifyVectors[] = {")
    for i in range(12):
        d = rng.randrange(1, N)
        qx, qy = public_point(d)
        digest = hashlib.sha256(f"verify {i}".encode()).digest()
        k = rng.randrange(1, N)  # a random nonce here: RFC 6979 is covered above
        r, s = sign_with_nonce(d, digest, k)
        flipped = bytes([digest[0] ^ 0x01]) + digest[1:]
        wrong_qx, wrong_qy = public_point(rng.randrange(1, N))
        cases = [
            (qx, qy, digest, r, s),                  # a good signature
            (qx, qy, digest, r, N - s),              # its high/low-s twin: also valid
            (qx, qy, flipped, r, s),                 # one bit of the digest changed
            (qx, qy, digest, (r + 1) % N or 1, s),   # r changed
            (qx, qy, digest, r, (s + 1) % N or 1),   # s changed
            (qx, qy, digest, s, r),                  # swapped
            (wrong_qx, wrong_qy, digest, r, s),      # another key
            (qx, qy, digest, 0, s),                  # r = 0
            (qx, qy, digest, r, 0),                  # s = 0
            (qx, qy, digest, N, s),                  # r = n
            (qx, qy, digest, r, N),                  # s = n
            (qx, qy, digest, r + N if r + N < 2**256 else 2**256 - 1, s),  # r + n: same mod n, out of range
            (qx, qy, digest, 1, 1),                  # in range, wrong
            (qx, qy, digest, N - 1, N - 1),          # in range, wrong
        ]
        for cqx, cqy, cd, cr, cs in cases:
            valid = openssl_accepts(cqx, cqy, cd, cr, cs)
            emit(f'    {{"{hex32(cqx)}", "{hex32(cqy)}", "{cd.hex().upper()}", "{hex32(cr)}", '
                 f'"{hex32(cs)}", {"true" if valid else "false"}}},')
    emit("};")
    emit("")

    # --- Points that are not on the curve, for from_uncompressed: {x, y} ------------------------
    emit("// {x, y}: coordinates that are not a point of P-256 (off the curve, or not below p)")
    emit("inline constexpr OffCurveVector kOffCurveVectors[] = {")
    gx, gy = public_point(1)
    off = [(gx, (gy + 1) % P), (gx + 1, gy), (0, 0), (1, 1), (P, gy), (gx, P), (P - 1, P - 1),
           (2**256 - 1, 2**256 - 1), (gx, gy ^ 1)]
    b = 0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B
    for x, y in off:
        # Make sure each really is excluded, so that a vector cannot become valid by accident.
        on_curve = x < P and y < P and (y * y - (x * x * x - 3 * x + b)) % P == 0
        assert not on_curve, (hex32(x), hex32(y))
        emit(f'    {{"{hex32(x)}", "{hex32(y)}"}},')
    emit("};")

    emit("")
    emit("// clang-format on")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
